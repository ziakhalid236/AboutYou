    /** Translates [word] into [lang]; returns it unchanged when unknown. */
    fun word(word: String, lang: Language): String {
        val row = WORDS[word.trim().lowercase()] ?: return word
        return row.getOrNull(lang.ordinal)?.takeIf { it.isNotBlank() } ?: word
    }

    /** Translates a comma separated list, keeping the ", " separator. */
    fun list(csv: String, lang: Language): String =
        csv.split(",")
            .joinToString(", ") { part -> word(part.trim(), lang) }
}
